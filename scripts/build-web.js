#!/usr/bin/env node
/**
 * Builds the hosted, serverless version of Hearthbeat into `dist/`.
 *
 * The app is normally a Node server, but a public demo should not share one
 * household between every visitor. So this build ships the interface plus the
 * application code itself (the same modules the server uses) and the page runs
 * everything in memory, per visitor. Nothing is sent anywhere.
 *
 *   dist/            the interface (public/)
 *   dist/engine/     browser-safe copies of server/core, server/sim, server/ring, hub, api, snapshot, local
 *   dist/js/mode.js  replaced with `export const STATIC = true;`
 *
 * The build fails if any copied file depends on Node.
 */
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

/** Server files that must NOT ship to the browser because they need Node. */
const NODE_ONLY = new Set(['sim/mock-api.js']);

rmSync(dist, { recursive: true, force: true });
cpSync(join(root, 'public'), dist, { recursive: true });

const engine = join(dist, 'engine');
mkdirSync(engine, { recursive: true });
for (const dir of ['core', 'sim', 'ring']) {
  cpSync(join(root, 'server', dir), join(engine, dir), {
    recursive: true,
    filter: (src) => !NODE_ONLY.has(relative(join(root, 'server'), src).split(sep).join('/')),
  });
}
for (const file of ['hub.js', 'api.js', 'snapshot.js', 'local.js']) {
  cpSync(join(root, 'server', file), join(engine, file));
}

writeFileSync(join(dist, 'js/mode.js'), '// Generated by scripts/build-web.js\nexport const STATIC = true;\n');

// Guard: nothing in the browser bundle may import a Node built-in.
const offenders = [];
(function scan(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) scan(full);
    else if (name.endsWith('.js')) {
      const text = readFileSync(full, 'utf8');
      if (/from\s+['"]node:|import\(\s*['"]node:|require\(/.test(text)) offenders.push(relative(dist, full));
    }
  }
})(dist);
if (offenders.length) {
  console.error(`Build failed: these files depend on Node and cannot run in a browser:\n  ${offenders.join('\n  ')}`);
  process.exit(1);
}

const count = (function walk(d) {
  return readdirSync(d).reduce((n, f) => n + (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : 1), 0);
})(dist);
console.log(`built dist/ (${count} files)`);
